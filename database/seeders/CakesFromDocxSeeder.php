    private function nutritionFor(string $name, string $composition): array
    {
        $text = mb_strtolower($name.' '.$composition);

        if (str_contains($text, 'наполеон') || str_contains($text, 'масло сливочное')) {
            return [
                'calories' => 380,
                'proteins' => 6.0,
                'fats' => 23.0,
                'carbohydrates' => 38.0,
            ];
        }

        if (str_contains($text, 'шоколадный бисквит')) {
            return [
                'calories' => 350,
                'proteins' => 5.5,
                'fats' => 17.0,
                'carbohydrates' => 43.0,
            ];
        }

        if (str_contains($text, 'фисташковое пюре') || str_contains($text, 'ягоды свежие')) {
            return [
                'calories' => 355,
                'proteins' => 5.5,
                'fats' => 18.0,
                'carbohydrates' => 40.0,
            ];
        }

        if (str_contains($text, 'манго')) {
            return [
                'calories' => 342,
                'proteins' => 5.0,
                'fats' => 15.5,
                'carbohydrates' => 42.0,
            ];
        }

        return [
            'calories' => 325,
            'proteins' => 5.0,
            'fats' => 14.0,
            'carbohydrates' => 40.0,
        ];
    }
